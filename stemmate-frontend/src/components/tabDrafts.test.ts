import assert from 'node:assert/strict';
import {DRAFT_KEY,DRAFT_TTL,clearTabDrafts,enableDrafts,readDrafts,saveDraft,removeDraft} from './tabDrafts';
const data=new Map<string,string>();
const storage={getItem:(key:string)=>data.get(key)??null,setItem:(key:string,value:string)=>{data.set(key,value);},removeItem:(key:string)=>{data.delete(key);}};
const draft={id:'chat:0:na-nssco:10:2027',label:'Mathematics',stage:'Your thinking',question:'2x+3=11',text:'Subtract 3.'};
const now=Date.now();
assert.equal(saveDraft(1,draft,storage,now),false);assert.equal(data.size,0);
assert.equal(enableDrafts(1,true,storage),true);
assert.equal(saveDraft(1,draft,storage,now),true);
assert.equal(readDrafts(1,storage,now).drafts[0].text,draft.text);
assert.equal(readDrafts(1,storage,now+DRAFT_TTL).drafts.length,0);
saveDraft(1,draft,storage,now);
assert.equal(readDrafts(2,storage,now).drafts.length,0);assert.equal(data.size,0);
enableDrafts(1,true,storage);
for(let i=0;i<8;i++)saveDraft(1,{...draft,id:String(i)},storage,now);
assert.equal(readDrafts(1,storage,now).drafts.length,4);
saveDraft(1,{...draft,id:'7',text:''},storage,now);assert.equal(readDrafts(1,storage,now).drafts.length,3);
removeDraft(1,'6',storage);assert.equal(readDrafts(1,storage,now).drafts.length,2);
clearTabDrafts(storage);assert.equal(data.size,0);
storage.setItem(DRAFT_KEY,'broken');assert.equal(readDrafts(1,storage).enabled,false);
storage.setItem(DRAFT_KEY,JSON.stringify({owner:1,enabled:true,drafts:[{...draft,expires:now+DRAFT_TTL,token:'DO_NOT_KEEP',image:'DO_NOT_KEEP'}]}));
readDrafts(1,storage,now);assert.doesNotMatch(storage.getItem(DRAFT_KEY)!,/DO_NOT_KEEP/);
const blocked={getItem:()=>{throw Error('Disabled');},setItem:()=>{throw Error('Quota');},removeItem:()=>{throw Error('Disabled');}};
assert.doesNotThrow(()=>readDrafts(1,blocked));assert.equal(enableDrafts(1,true,blocked),false);assert.equal(saveDraft(1,draft,blocked),false);
console.log('Tab draft opt-in, owner isolation, expiry, cap, allowlist, clearing and blocked-storage behaviour passed.');

clearTabDrafts(storage);enableDrafts(1,true,storage);saveDraft(1,draft,storage,now);
const original=storage.getItem(DRAFT_KEY);
const quota={...storage,setItem:()=>{throw Error('Quota');}};
assert.equal(readDrafts(1,quota,now).drafts[0].text,draft.text);
assert.equal(saveDraft(1,{...draft,text:'New unsaved text'},quota,now),false);
assert.equal(storage.getItem(DRAFT_KEY),original);
